#!/usr/bin/env python3
"""Check that every paper alias in Papers/<Paper>/<Paper>.lean is literally a certified theorem (run after tools/certify.py check).

    python3 tools/check_aliases.py [--no-build]

Fails unless ALL of:
  1. textual: every alias file consists only of the generator's header comment, `import StatFormal....` lines, a module docstring,
     `namespace`/`end` lines, docstrings and declarations of the exact form `theorem <alias> : <claim> := <theorem>` where
     (claim, theorem) is a target of certify/targets.toml; no other command (no `set_option`, `attribute`, `axiom`, macro, ...);
  2. completeness: every target whose paper has a Papers/ page (PAPERS below) has at least one alias;
  3. `lake build Papers` succeeds;
  4. in Lean (kernel environment, not syntax): each alias constant is a theorem whose type is the constant <claim> and whose value is
     the constant <theorem> (so it is the frozen theorem itself, under the frozen claim; its axioms are the ones the gate checked).
"""
import os
import pathlib
import re
import subprocess
import sys
import tomllib

# The two paper pages of this repository (the development repository generates these from tools/gen_papers_face.py).
PAPERS = {"TrimmedMMD": (["trimmed-mmd"],), "TrimmedMMDJMLR": (["trimmed-mmd (jmlr)"],)}


def paper_tags_match(tag, wanted):
    """'otfd B/C' counts for 'otfd B' and 'otfd C' (shared tags)."""
    if tag == wanted:
        return True
    tp, _, tl = tag.rpartition(" ")
    wp, _, wl = wanted.rpartition(" ")
    return tp == wp and "/" in tl and wl in tl.split("/")

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENV = dict(os.environ, PATH=str(pathlib.Path.home() / ".elan/bin") + ":" + os.environ["PATH"])
DECL = re.compile(r"^theorem ([\w.']+) : ([\w.']+) := ([\w.']+)$")


def parse(f):
    """[(alias full name, claim, theorem)] or raises ValueError on anything the generator does not write."""
    s = f.read_text()
    s = re.sub(r"/-[-!].*?-/", "", s, flags=re.S)                 # docstrings and the module docstring
    ns, out = None, []
    for i, line in enumerate(s.splitlines(), 1):
        if not line.strip() or line.startswith("-- Generated by tools/gen_papers_face.py"):  # header of the generated pages
            continue
        if re.fullmatch(r"import StatFormal\.[\w.]+", line):
            continue
        m = re.fullmatch(r"namespace (Papers\.\w+)", line)
        if m and ns is None:
            ns = m.group(1)
            continue
        if ns and line == f"end {ns}":
            ns = "<closed>"
            continue
        m = DECL.match(line)
        if m and ns and ns != "<closed>":
            out.append((f"{ns}.{m.group(1)}", m.group(2), m.group(3)))
            continue
        raise ValueError(f"{f.relative_to(ROOT)}:{i}: unexpected line: {line[:120]}")
    return out


def main():
    targets = tomllib.loads((ROOT / "certify/targets.toml").read_text())["target"]
    pairs = {(t["claim"], t["theorem"]) for t in targets}
    paged = [t for t in targets if any(paper_tags_match(t["paper"], w) for spec in PAPERS.values() for w in spec[0])]
    need = {(t["claim"], t["theorem"]) for t in paged}
    fails, aliases = [], []
    files = sorted((ROOT / "Papers").glob("*/*.lean"))
    for f in files:
        try:
            for a, c, t in parse(f):
                if (c, t) not in pairs:
                    fails.append(f"{f.relative_to(ROOT)}: alias {a} : {c} := {t} is not a target of certify/targets.toml")
                aliases.append((a, c, t))
        except ValueError as e:
            fails.append(str(e))
    have = {(c, t) for _, c, t in aliases}
    missing = sorted(need - have)
    if missing:
        fails.append(f"{len(missing)} targets without an alias, e.g. {missing[:3]}")
    if len({a for a, _, _ in aliases}) != len(aliases):
        fails.append("duplicate alias names")
    if not fails and "--no-build" not in sys.argv:
        b = subprocess.run(["lake", "build", "Papers"], cwd=ROOT, env=ENV, capture_output=True, text=True)
        if b.returncode != 0:
            fails.append("lake build Papers failed:\n" + b.stdout[-3000:] + b.stderr[-2000:])
    if not fails and "--no-build" not in sys.argv:
        tsv = ROOT / ".check_aliases_audit.tsv"     # data read at run time (a 3000-element literal overflows the compiler)
        tsv.write_text("".join(f"{a}\t{c}\t{t}\n" for a, c, t in aliases))
        audit = f"""import Papers
open Lean in
#eval show CoreM Unit from do
  let env ← getEnv
  let lines ← IO.FS.lines "{tsv}"
  let mut bad := 0
  let mut n := 0
  for l in lines do
    match l.splitOn "\t" with
    | [a, c, t] =>
      n := n + 1
      let (a, c, t) := (a.toName, c.toName, t.toName)
      match env.find? a with
      | some (.thmInfo v) =>
        let okT := match v.type with | .const k _ => k == c | _ => false
        let okV := match v.value with | .const k _ => k == t | _ => false
        unless okT && okV do
          IO.println s!"ALIAS MISMATCH {{a}}"
          bad := bad + 1
      | _ =>
        IO.println s!"ALIAS MISSING {{a}}"
        bad := bad + 1
    | _ => bad := bad + 1
  IO.println s!"ALIASES CHECKED {{n}} BAD {{bad}}"
"""
        af = ROOT / ".check_aliases_audit.lean"
        af.write_text(audit)
        r = subprocess.run(["lake", "env", "lean", str(af)], cwd=ROOT, env=ENV, capture_output=True, text=True)
        af.unlink()
        tsv.unlink()
        out = r.stdout + r.stderr
        m = re.search(r"ALIASES CHECKED (\d+) BAD (\d+)", out)
        if r.returncode != 0 or re.search(r":\d+:\d+: error", out) or not m or m.group(2) != "0" or int(m.group(1)) != len(aliases):
            fails.append("Lean alias audit failed:\n" + out[-3000:])
    if fails:
        print("ALIAS CHECK FAILED\n" + "\n".join(" - " + f for f in fails))
        sys.exit(1)
    print(f"ALIASES OK: {len(aliases)} aliases in {len(files)} paper files; each is literally a certified theorem under its frozen "
          f"claim; all {len(paged)} targets of the {len(PAPERS)} paper pages covered ({len(targets) - len(paged)} targets have no page)")


if __name__ == "__main__":
    main()
